/** Numeric aliases preserve level summaries and earlier integrations. */
export const lessons = Object.fromEntries(authoredLessons.map(lesson => [lesson.id, lesson]));
for (const levelId of [1, 2, 3, 4, 5]) lessons[levelId] = lessons[`${levelId}-main`];

export function getLesson(id) {
  if ((typeof id !== 'string' && typeof id !== 'number') || !Object.hasOwn(lessons, id)) return undefined;
  return lessons[id];
}
export function getLevelLessons(levelId) { return levelLessons[levelId] || []; }
